/* Regenerates lib/legacy-version.ts from the CONTENT of the legacy scripts.
   Runs as part of `npm run build` (prebuild), so the cache-busting query in
   the <script> URLs always matches what is actually in public/legacy.

   Why content hashes and not a build id: these files sit on an unversioned URL
   behind a 4-hour public max-age, so a shipped fix could take hours to reach a
   visitor who already had the page. A build id would also change the URL on
   every deploy even when the scripts did not, needlessly discarding a warm
   cache. NEXT_PUBLIC_BUILD_ID is not an option — Next does not populate it, so
   it compiles to the literal "?v=undefined" and the URL is stable again. */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILES = ["hermes-dock", "hermes-config", "uc-demo"];

const entries = FILES.map((name) => {
  const buf = readFileSync(join(root, "public", "legacy", `${name}.js`));
  const hash = createHash("sha1").update(buf).digest("hex").slice(0, 8);
  return [name, hash];
});

const body = `/* GENERATED by scripts/stamp-legacy.mjs — do not edit by hand.
   Content hashes of the legacy scripts, used to cache-bust their URLs. */
export const LEGACY_V = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;
`;

writeFileSync(join(root, "lib", "legacy-version.ts"), body);
console.log("stamped legacy versions:", Object.fromEntries(entries));
